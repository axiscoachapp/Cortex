-- Private physician decision + atomic effective grant bridge. Public API/UI and
-- removal of never-reviewed legacy grants are a separate, required cutover.
begin;
set transaction isolation level read committed;
set local lock_timeout='2s';
lock table cortex_private.reception_delegation_requests,cortex_private.reception_delegation_operations,
 public.staff_doctor_scopes in access exclusive mode nowait;
lock table public.clinics,public.clinic_members,public.clinic_staff_members,
 auth.users,public.account_deletion_requests in share row exclusive mode nowait;

-- Match the predecessor structurally, rather than relying on autogenerated
-- constraint names. Fail atomically if its expected shape has changed.
do $$ declare c record;n integer:=0;begin
 for c in select conname from pg_constraint where conrelid='cortex_private.reception_delegation_requests'::regclass
  and contype='c' and pg_get_constraintdef(oid) like '%state%' loop
  execute format('alter table cortex_private.reception_delegation_requests drop constraint %I',c.conname);n:=n+1;
 end loop;
 if n<>2 then raise exception 'Unexpected delegation state constraints';end if;
 n:=0;
 for c in select conname from pg_constraint where conrelid='cortex_private.reception_delegation_requests'::regclass
  and contype='c' and conkey=array[(select attnum from pg_attribute where attrelid='cortex_private.reception_delegation_requests'::regclass and attname='end_reason')]::smallint[] loop
  execute format('alter table cortex_private.reception_delegation_requests drop constraint %I',c.conname);n:=n+1;
 end loop;
 if n<>1 then raise exception 'Unexpected delegation end reason constraint';end if;
end $$;
alter table cortex_private.reception_delegation_requests
 add column decided_at timestamptz,
 add column decided_by uuid references auth.users(id) on delete restrict,
 add constraint delegation_decider check(decided_by is null or decided_by=doctor_user_id),
 add constraint delegation_end_reason check(end_reason in ('withdrawn','member_inactive','denied','scope_removed')),
 add constraint delegation_state check(state in ('pending','approved','denied','cancelled','revoked')),
 add constraint delegation_shape check(
  (state='pending' and revision=1 and decided_at is null and decided_by is null and ended_at is null and ended_by is null and end_reason is null)
  or (state='cancelled' and revision=2 and decided_at is null and decided_by is null and ended_at is not null and ended_at>=created_at and end_reason is not null and end_reason in ('withdrawn','member_inactive'))
  or (state='approved' and revision=2 and decided_at is not null and decided_at>=created_at and decided_by is not null and ended_at is null and ended_by is null and end_reason is null)
  or (state='denied' and revision=2 and decided_at is not null and decided_at>=created_at and decided_by is not null and ended_at=decided_at and ended_at is not null and ended_by is not null and ended_by=decided_by and end_reason is not null and end_reason='denied')
  or (state='revoked' and revision=3 and decided_at is not null and decided_at>=created_at and decided_by is not null and ended_at is not null and ended_at>=decided_at and end_reason is not null and end_reason in ('withdrawn','member_inactive','scope_removed'))),
 add constraint delegation_grant_identity unique(id,clinic_id,staff_user_id,doctor_user_id);
drop index cortex_private.reception_pending_delegation_pair;
create unique index reception_current_delegation_pair on cortex_private.reception_delegation_requests(clinic_id,staff_user_id,doctor_user_id)
 where state in ('pending','approved');
alter table public.staff_doctor_scopes add column delegation_request_id uuid,
 add constraint scope_delegation_identity foreign key(delegation_request_id,clinic_id,staff_user_id,doctor_user_id)
 references cortex_private.reception_delegation_requests(id,clinic_id,staff_user_id,doctor_user_id) on delete restrict,
 add constraint scope_single_delegation unique(delegation_request_id);

create function cortex_private.reception_delegation_physician(p_clinic uuid,p_doctor uuid) returns uuid
language plpgsql volatile security definer set search_path='' as $$
declare actor uuid:=cortex_private.reception_delegation_actor(null);
begin
 if actor is distinct from p_doctor then raise exception 'Delegation physician unavailable' using errcode='42501';end if;
 perform 1 from public.clinic_members where clinic_id=p_clinic and user_id=actor and status='active' for share nowait;
 if not found then raise exception 'Delegation physician unavailable' using errcode='42501';end if;
 return actor;
exception when lock_not_available then
 raise exception 'Delegation authority changed concurrently; retry the transaction' using errcode='40001';
end $$;
create function cortex_private.reception_delegation_withdrawer(p_clinic uuid,p_doctor uuid) returns uuid
language plpgsql volatile security definer set search_path='' as $$
begin
 if auth.uid()=p_doctor then return cortex_private.reception_delegation_physician(p_clinic,p_doctor);end if;
 return cortex_private.reception_delegation_actor(p_clinic);
end $$;

create or replace function cortex_private.guard_reception_delegation_request() returns trigger
language plpgsql volatile security definer set search_path='' as $$
begin
 if tg_op='DELETE' then raise exception 'Delegation history immutable' using errcode='22023';end if;
 if tg_op='UPDATE' then
  if (new.id,new.clinic_id,new.staff_user_id,new.doctor_user_id,new.requested_by,new.capability_version,new.created_at)
   is distinct from (old.id,old.clinic_id,old.staff_user_id,old.doctor_user_id,old.requested_by,old.capability_version,old.created_at)
   or new.revision<>old.revision+1
   or not ((old.state='pending' and new.state in ('approved','denied','cancelled')) or (old.state='approved' and new.state='revoked'))
   or (old.state='approved' and (new.decided_at,new.decided_by) is distinct from (old.decided_at,old.decided_by))
   or (new.state in ('approved','denied') and (new.decided_at is null or new.decided_by is null)) then
   raise exception 'Delegation identity or transition invalid' using errcode='22023';end if;
 elsif new.state<>'pending' or new.revision<>1 or new.created_at is distinct from transaction_timestamp()
  or new.capability_version<>'clinic_reception_v1' then
  raise exception 'Delegation identity or transition invalid' using errcode='22023';
 end if;
 return new;
end $$;
drop trigger custody_reference on cortex_private.reception_delegation_requests;
create trigger custody_reference after insert or update on cortex_private.reception_delegation_requests
 for each row execute function cortex_private.guard_custody_reference('staff_user_id','doctor_user_id','requested_by','ended_by','decided_by');

create or replace function cortex_private.validate_reception_delegation_request() returns trigger
language plpgsql volatile security definer set search_path='' as $$
declare actor uuid;
begin
 -- AFTER custody_reference: account epochs precede fresh authority reads.
 if tg_op='INSERT' then
  actor:=cortex_private.reception_delegation_actor(new.clinic_id);
  if new.requested_by<>actor or not cortex_private.reception_delegation_eligible(new.clinic_id,new.staff_user_id,new.doctor_user_id) then
   raise exception 'Delegation member unavailable' using errcode='42501';end if;
 elsif new.end_reason='member_inactive' and new.ended_by is null
  and not cortex_private.reception_delegation_eligible(new.clinic_id,new.staff_user_id,new.doctor_user_id) then null;
 elsif new.state='revoked' and new.end_reason='scope_removed' and new.ended_by is null and not exists(
  select 1 from public.staff_doctor_scopes where delegation_request_id=new.id) then null;
 elsif new.state in ('approved','denied') then
  actor:=cortex_private.reception_delegation_physician(new.clinic_id,new.doctor_user_id);
  if new.decided_by is distinct from actor or not cortex_private.reception_delegation_eligible(new.clinic_id,new.staff_user_id,new.doctor_user_id) then
   raise exception 'Delegation member unavailable' using errcode='42501';end if;
 elsif new.state='cancelled' then
  actor:=cortex_private.reception_delegation_actor(new.clinic_id);
  if new.end_reason is distinct from 'withdrawn' or new.ended_by is distinct from actor then raise exception 'Delegation administration unavailable' using errcode='42501';end if;
 else
  actor:=cortex_private.reception_delegation_withdrawer(new.clinic_id,new.doctor_user_id);
  if new.end_reason is distinct from 'withdrawn' or new.ended_by is distinct from actor then raise exception 'Delegation administration unavailable' using errcode='42501';end if;
 end if;
 -- Keep the effective grant in this very statement, including privileged
 -- updates. Explicit physician approval can adopt an existing legacy grant.
 if new.state='approved' then
  insert into public.staff_doctor_scopes(clinic_id,staff_user_id,doctor_user_id,delegation_request_id)
   values(new.clinic_id,new.staff_user_id,new.doctor_user_id,new.id)
   on conflict(clinic_id,staff_user_id,doctor_user_id) do update set delegation_request_id=excluded.delegation_request_id;
 elsif new.state='denied' then
  delete from public.staff_doctor_scopes where clinic_id=new.clinic_id and staff_user_id=new.staff_user_id and doctor_user_id=new.doctor_user_id;
 elsif new.state='revoked' then
  delete from public.staff_doctor_scopes where delegation_request_id=new.id;
 end if;
 return null;
end $$;

create function cortex_private.guard_delegation_scope_identity() returns trigger
language plpgsql security definer set search_path='' as $$
begin
 if old.delegation_request_id is not null and
  (new.delegation_request_id,new.clinic_id,new.staff_user_id,new.doctor_user_id) is distinct from
  (old.delegation_request_id,old.clinic_id,old.staff_user_id,old.doctor_user_id) then
  raise exception 'Delegation grant identity immutable' using errcode='22023';end if;
 return new;
end $$;
create trigger delegation_scope_identity before update on public.staff_doctor_scopes
 for each row execute function cortex_private.guard_delegation_scope_identity();
create function cortex_private.validate_delegation_scope() returns trigger
language plpgsql volatile security definer set search_path='' as $$
begin
 if new.delegation_request_id is null then
  -- Transitional compatibility only for pairs with no physician decision yet.
  -- Once reviewed, an old array setter cannot bypass a denial/revocation.
  if exists(select 1 from cortex_private.reception_delegation_requests where clinic_id=new.clinic_id
   and staff_user_id=new.staff_user_id and doctor_user_id=new.doctor_user_id and decided_at is not null) then
   raise exception 'Delegation physician approval required' using errcode='42501';end if;
 else
  if not exists(select 1 from cortex_private.reception_delegation_requests where id=new.delegation_request_id
   and clinic_id=new.clinic_id and staff_user_id=new.staff_user_id and doctor_user_id=new.doctor_user_id and state='approved') then
   raise exception 'Delegation physician approval required' using errcode='42501';end if;
  perform cortex_private.reception_delegation_physician(new.clinic_id,new.doctor_user_id);
 end if;
 return null;
end $$;
create trigger zz_delegation_scope after insert or update on public.staff_doctor_scopes
 for each row execute function cortex_private.validate_delegation_scope();
create function cortex_private.close_delegation_scope() returns trigger
language plpgsql volatile security definer set search_path='' as $$
begin
 -- The scope row is already locked. Acquire accounts NOWAIT before taking
 -- the request row, opposite-side approval/revocation must never deadlock.
 perform cortex_private.touch_custody_epoch(array[old.staff_user_id,old.doctor_user_id]);
 if old.delegation_request_id is not null then
  update cortex_private.reception_delegation_requests set state='revoked',revision=revision+1,
   ended_at=clock_timestamp(),ended_by=null,end_reason='scope_removed'
   where id=old.delegation_request_id and state='approved';
 end if;
 return null;
end $$;
create trigger delegation_scope_removed after delete on public.staff_doctor_scopes
 for each row execute function cortex_private.close_delegation_scope();

create or replace function cortex_private.guard_reception_delegation_operation() returns trigger
language plpgsql volatile security definer set search_path='' as $$
declare r cortex_private.reception_delegation_requests;actor uuid;k text:=new.payload->>'kind';valid boolean:=false;
begin
 if tg_op<>'INSERT' then raise exception 'Delegation history immutable' using errcode='22023';end if;
 select * into r from cortex_private.reception_delegation_requests where id=new.request_id;
 if not found then raise exception 'Delegation unavailable' using errcode='42501';end if;
 if k in ('approve','deny') then actor:=cortex_private.reception_delegation_physician(r.clinic_id,r.doctor_user_id);
 elsif k='revoke' then actor:=cortex_private.reception_delegation_withdrawer(r.clinic_id,r.doctor_user_id);
 else actor:=cortex_private.reception_delegation_actor(r.clinic_id);end if;
 if k='request' then valid:=r.state in ('pending','approved') and new.payload=jsonb_build_object('kind',k,'clinic',r.clinic_id,'staff',r.staff_user_id,'doctor',r.doctor_user_id);
 elsif k='cancel' then valid:=r.state='cancelled' and r.ended_by=actor and new.payload=jsonb_build_object('kind',k,'request',r.id,'expected',r.revision-1);
 elsif k in ('approve','deny') then valid:=r.state=case k when 'approve' then 'approved' else 'denied' end and r.decided_by=actor and new.payload=jsonb_build_object('kind',k,'request',r.id,'expected',r.revision-1);
 elsif k='revoke' then valid:=r.state='revoked' and r.ended_by=actor and r.end_reason='withdrawn' and new.payload=jsonb_build_object('kind',k,'request',r.id,'expected',r.revision-1);
 end if;
 if actor<>new.actor_user_id or new.result_revision<>r.revision or valid is not true then raise exception 'Delegation operation mismatch' using errcode='22023';end if;
 return null;
end $$;

-- Preserve request replay and aliases on the current approved instance. An
-- operation bound to a terminal instance never creates a replacement request.
do $$ declare definition text;begin
 definition:=pg_get_functiondef('cortex_private.request_reception_delegation(uuid,uuid,uuid,uuid)'::regprocedure);
 if position('if r.state<>''pending'' then' in definition)=0 or position('and state=''pending'';' in definition)=0 then raise exception 'Unexpected delegation request function';end if;
 execute replace(replace(definition,'if r.state<>''pending'' then','if r.state not in (''pending'',''approved'') then'),
  'and state=''pending'';','and state in (''pending'',''approved'');');
end $$;
create function cortex_private.decide_reception_delegation(p_request uuid,p_revision integer,p_decision text,p_operation uuid) returns jsonb
language plpgsql volatile security definer set search_path='' as $$
declare actor uuid:=cortex_private.reception_delegation_actor(null);r cortex_private.reception_delegation_requests;
 previous cortex_private.reception_delegation_operations;body jsonb:=jsonb_build_object('kind',p_decision,'request',p_request,'expected',p_revision);t timestamptz;
begin
 if p_request is null or p_revision is null or p_revision<1 or p_decision is null or p_decision not in ('approve','deny') or p_operation is null then raise exception 'Invalid delegation input' using errcode='22023';end if;
 select * into r from cortex_private.reception_delegation_requests where id=p_request;
 if not found then raise exception 'Delegation unavailable' using errcode='42501';end if;
 perform cortex_private.reception_delegation_physician(r.clinic_id,r.doctor_user_id);
 select * into r from cortex_private.reception_delegation_requests where id=p_request for update;
 perform cortex_private.touch_custody_epoch(array[actor,r.staff_user_id,r.doctor_user_id,r.requested_by]);
 perform cortex_private.reception_delegation_physician(r.clinic_id,r.doctor_user_id);
 if not cortex_private.reception_delegation_eligible(r.clinic_id,r.staff_user_id,r.doctor_user_id) then raise exception 'Delegation member unavailable' using errcode='42501';end if;
 select * into previous from cortex_private.reception_delegation_operations where actor_user_id=actor and operation_id=p_operation;
 if found then
  if previous.payload<>body then raise exception 'Delegation operation mismatch' using errcode='22023';end if;
  if previous.request_id<>r.id or previous.result_revision<>r.revision or r.state<>(case p_decision when 'approve' then 'approved' else 'denied' end) then raise exception 'Delegation changed' using errcode='40001';end if;
  return cortex_private.reception_delegation_snapshot(r);
 end if;
 if r.state<>'pending' or r.revision<>p_revision then raise exception 'Delegation changed' using errcode='40001';end if;
 t:=clock_timestamp();
 update cortex_private.reception_delegation_requests set state=case p_decision when 'approve' then 'approved' else 'denied' end,
  revision=revision+1,decided_at=t,decided_by=actor,ended_at=case when p_decision='deny' then t end,
  ended_by=case when p_decision='deny' then actor end,end_reason=case when p_decision='deny' then 'denied' end where id=p_request returning * into r;
 insert into cortex_private.reception_delegation_operations values(actor,p_operation,r.id,body,r.revision);
 return cortex_private.reception_delegation_snapshot(r);
end $$;
create function cortex_private.revoke_reception_delegation(p_request uuid,p_revision integer,p_operation uuid) returns jsonb
language plpgsql volatile security definer set search_path='' as $$
declare actor uuid:=cortex_private.reception_delegation_actor(null);r cortex_private.reception_delegation_requests;
 previous cortex_private.reception_delegation_operations;body jsonb:=jsonb_build_object('kind','revoke','request',p_request,'expected',p_revision);
begin
 if p_request is null or p_revision is null or p_revision<1 or p_operation is null then raise exception 'Invalid delegation input' using errcode='22023';end if;
 select * into r from cortex_private.reception_delegation_requests where id=p_request;
 if not found then raise exception 'Delegation unavailable' using errcode='42501';end if;
 perform cortex_private.reception_delegation_withdrawer(r.clinic_id,r.doctor_user_id);
 select * into r from cortex_private.reception_delegation_requests where id=p_request for update;
 perform cortex_private.touch_custody_epoch(array[actor,r.staff_user_id,r.doctor_user_id,r.requested_by]);
 perform cortex_private.reception_delegation_withdrawer(r.clinic_id,r.doctor_user_id);
 select * into previous from cortex_private.reception_delegation_operations where actor_user_id=actor and operation_id=p_operation;
 if found then
  if previous.payload<>body then raise exception 'Delegation operation mismatch' using errcode='22023';end if;
  if previous.request_id<>r.id or previous.result_revision<>r.revision or r.state<>'revoked' then raise exception 'Delegation changed' using errcode='40001';end if;
  return cortex_private.reception_delegation_snapshot(r);
 end if;
 if r.state<>'approved' or r.revision<>p_revision then raise exception 'Delegation changed' using errcode='40001';end if;
 update cortex_private.reception_delegation_requests set state='revoked',revision=revision+1,ended_at=clock_timestamp(),ended_by=actor,end_reason='withdrawn' where id=p_request returning * into r;
 insert into cortex_private.reception_delegation_operations values(actor,p_operation,r.id,body,r.revision);
 return cortex_private.reception_delegation_snapshot(r);
end $$;
create or replace function cortex_private.close_reception_delegation_requests() returns trigger
language plpgsql volatile security definer set search_path='' as $$
begin
 perform cortex_private.touch_custody_epoch(array[new.user_id]);
 update cortex_private.reception_delegation_requests r set state=case state when 'pending' then 'cancelled' else 'revoked' end,
  revision=revision+1,ended_at=clock_timestamp(),ended_by=null,end_reason='member_inactive'
  where r.clinic_id=new.clinic_id and r.state in ('pending','approved')
  and (case tg_table_name when 'clinic_staff_members' then r.staff_user_id=new.user_id else r.doctor_user_id=new.user_id end);
 return null;
end $$;
-- decided_by is constrained to doctor_user_id, already in the immutable
-- preflight inventory; custody_reference additionally fences the explicit FK.
revoke all on function cortex_private.reception_delegation_physician(uuid,uuid),cortex_private.reception_delegation_withdrawer(uuid,uuid),
 cortex_private.guard_delegation_scope_identity(),cortex_private.validate_delegation_scope(),cortex_private.close_delegation_scope(),
 cortex_private.decide_reception_delegation(uuid,integer,text,uuid),cortex_private.revoke_reception_delegation(uuid,integer,uuid)
 from public,anon,authenticated,service_role;
commit;
